// Regenerates src/lib/agreement/partnership-agreement.template.ts from the source .docx.
// Run this again only if legal-source/partnership-agreement-source.docx changes.
// Converts the .docx to HTML mechanically (mammoth) — the legal text is never retyped by hand.
//
// Written as a plain .ts module exporting a string constant (not a separate .html asset read via
// fs/`?raw` at import time) so it imports identically under Vite (bundled into the app) and under
// plain Node/tsx (used by this repo's standalone test scripts) — a runtime file read of a sibling
// .html asset did not survive this app's Vercel deployment.
import mammoth from "mammoth";
import { writeFileSync } from "fs";

const SOURCE = "legal-source/partnership-agreement-source.docx";
const OUT = "src/lib/agreement/partnership-agreement.template.ts";

const { value: html, messages } = await mammoth.convertToHtml({ path: SOURCE });
if (messages.length) console.warn("mammoth messages:", messages);

// Sanity checks: the known blank-fill anchors must still be present, unmodified by hand.
const required = [
  "Second: (_____), Commercial Registration No.: (_____), Tax Number: (_____), Address: (_____), Email: (_____), represented by/in the capacity of: (_____).",
  "ثانياً: ()، السجل التجاري: () الرقم الضريبي: () العنوان: () البريد الإلكتروني: () ويمثلها/ بصفته ().",
  "On this day corresponding to ___ /___ /___ H, an agreement was concluded between:",
  "إنه في يوم الموافق / /هـ تم الاتفاق بين كل من:",
];
for (const marker of required) {
  if (!html.includes(marker))
    throw new Error(`Template is missing an expected anchor: "${marker}"`);
}

const out = `// Generated by scripts/build-agreement-template.mjs from legal-source/partnership-agreement-source.docx.
// Do not edit by hand — re-run that script if the source document changes.
export const partnershipAgreementTemplate = ${JSON.stringify(html)};
`;
writeFileSync(OUT, out, "utf8");
console.log(`Wrote ${OUT} (${html.length} chars)`);
